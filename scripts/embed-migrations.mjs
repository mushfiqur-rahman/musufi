// Copies db/migrations/*.sql into lib/migrations.generated.ts so the server can
// apply them without reading files at runtime (hosting may run the app from a
// different folder). Runs automatically before every build ("prebuild").
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "db", "migrations");
const list = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()
  .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8").replace(/\r\n/g, "\n") }));
const out = `// GENERATED by scripts/embed-migrations.mjs from db/migrations. Do not edit.
export const MIGRATIONS: readonly { name: string; sql: string }[] = ${JSON.stringify(list, null, 2)};
`;
writeFileSync(join(root, "lib", "migrations.generated.ts"), out);
console.log(`embedded ${list.length} migrations`);
